// Print-only 80mm POS-style "BILLING SUMMARY RECEIPT".
// Used by the By Ref tab — totals only, no client list, no breakdown.
// Same design language as the invoice POS receipt.

export type ByRefSummary = {
  total_count: number;
  total_clients: number;
  total_subtotal: number;
  total_previous: number;
  total_payable: number;
  total_discount: number;
  total_amount: number;
};

export type ByRefPosData = {
  company?:
    | {
        company_name?: string | null;
        address?: string | null;
        phone?: string | null;
        bank_name?: string | null;
        bank_branch?: string | null;
        bank_account_number?: string | null;
      }
    | null;
  reference_name: string;
  billing_month_label: string;
  area_label?: string;
  summary: ByRefSummary;
  generated_by?: string;
  generated_on?: string;
};

const esc = (v: unknown) =>
  String(v ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const fmt = (n: number | string | null | undefined) =>
  Number(n ?? 0).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

function nowStamp(): string {
  const d = new Date();
  const pad = (x: number) => String(x).padStart(2, "0");
  return `${pad(d.getDate())}-${d.toLocaleString("en-US", { month: "short" })}-${d.getFullYear()} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

export function buildByRefPosHtml(data: ByRefPosData): string {
  const { company, reference_name, billing_month_label, summary, generated_by } = data;
  const generated_on = data.generated_on || nowStamp();
  const netPayable = Math.max(
    0,
    Number(summary.total_payable || 0) - Number(summary.total_discount || 0),
  );

  const rows: Array<[string, string]> = [
    ["Total Clients", String(summary.total_clients)],
    ["Total Bills", String(summary.total_count)],
    ["Billing Amount", fmt(summary.total_subtotal)],
    ["Previous Balance", fmt(summary.total_previous)],
    ["Total Payable", fmt(summary.total_payable)],
    ["Discount", fmt(summary.total_discount)],
  ];

  const rowsHtml = rows
    .map(
      ([l, v], i) =>
        `<div class="row"><span>${esc(l)}</span><span>${esc(v)}</span></div>${
          i < rows.length - 1 ? `<div class="dash-sub"></div>` : ""
        }`,
    )
    .join("");

  return `
    <div class="paper">
      ${company?.company_name ? `<div class="center company">${esc(company.company_name)}</div>` : ""}
      ${company?.address ? `<div class="center muted">${esc(company.address)}</div>` : ""}
      ${company?.phone ? `<div class="center muted">Mobile: ${esc(company.phone)}</div>` : ""}
      <div class="dash"></div>
      <div class="center title">BILLING SUMMARY</div>
      <div class="dash"></div>
      <div class="row"><span>Tax Period</span><span>${esc(billing_month_label)}</span></div>
      <div class="row"><span>Reference</span><span>${esc(reference_name || "All")}</span></div>
      <div class="dash"></div>
      ${rowsHtml}
      <div class="dash"></div>
      <div class="row net"><span>NET PAYABLE</span><span>${esc(fmt(netPayable))}</span></div>
      <div class="dash"></div>
      ${
        company?.bank_account_number || company?.bank_name
          ? `<div class="pay-title">Please Pay to:</div>
             ${company?.company_name ? `<div class="pay-line">A/C Name: ${esc(company.company_name)}</div>` : ""}
             ${company?.bank_account_number ? `<div class="pay-line">A/C No: ${esc(company.bank_account_number)}</div>` : ""}
             ${company?.bank_name ? `<div class="pay-line">Bank: ${esc(company.bank_name)}</div>` : ""}
             ${company?.bank_branch ? `<div class="pay-line">Branch: ${esc(company.bank_branch)}</div>` : ""}
             <div class="dash"></div>`
          : ""
      }
      <div class="muted small">Generated By : ${esc(generated_by || "—")}</div>
      <div class="muted small">Generated On : ${esc(generated_on)}</div>
      <div class="dash"></div>
      <div class="center thanks">THANK YOU</div>
      <div class="dash"></div>
      <div class="bottom-space"></div>
    </div>
  `;
}

